function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function linkify(text) {
  const safe = esc(text);
  return /^https?:\/\/\S+$/.test(String(text))
    ? `<a href="${safe}" rel="noopener noreferrer">${safe}</a>`
    : safe;
}

function hostOf(url) {
  try {
    return new URL(url).hostname;
  } catch {
    return url;
  }
}

function slug(url) {
  return String(url).replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').slice(0, 60).toLowerCase();
}

function fmt(value, unit) {
  if (unit === 'bytes') return formatBytes(Number(value));
  if (unit === 'ms') return `${Math.round(Number(value))}ms`;
  if (unit === 'score') return Number(value).toFixed(3);
  return String(value);
}
