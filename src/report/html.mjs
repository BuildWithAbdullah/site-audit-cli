import { SEVERITIES } from '../util/severity.mjs';
import { formatBytes } from '../checks/performance.mjs';

/**
 * A single self-contained HTML file, because a report that needs a build step
 * or a CDN is a report a client cannot open in two years.
 *
 * The report is itself held to the standard it measures: one h1, a heading
 * outline with no skipped levels, a skip link, visible focus on both colour
 * schemes, severity never carried by colour alone, a keyboard-reachable
 * scroll container for every evidence block, and no JavaScript. An
 * accessibility report that fails an accessibility audit is not an argument
 * anyone should have to have with a client.
 */
export function renderHtml(report) {
  const counts = report.summary.bySeverity;
  const generated = new Date(report.startedAt).toUTCString();

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Site audit: ${esc(hostOf(report.target))}</title>
<style>${STYLE}</style>
</head>
<body>
<a class="skip" href="#content">Skip to report</a>
<header class="masthead">
  <p class="eyebrow">Site audit</p>
  <h1>${esc(report.target)}</h1>
  <p class="meta">${report.summary.pagesAudited} page${report.summary.pagesAudited === 1 ? '' : 's'}
    &middot; ${esc(report.modules.join(', '))}
    &middot; ${esc(generated)}</p>
</header>

<main id="content">
  <section aria-labelledby="summary-heading">
    <h2 id="summary-heading">Summary</h2>
    <ul class="tiles">
      ${SEVERITIES.filter((s) => s !== 'info')
        .map(
          (s) => `<li class="tile sev-${s}">
        <span class="tile-value">${counts[s] ?? 0}</span>
        <span class="tile-label">${s}</span>
      </li>`,
        )
        .join('\n      ')}
      <li class="tile sev-manual">
        <span class="tile-value">${report.summary.manualChecksOutstanding}</span>
        <span class="tile-label">manual checks outstanding</span>
      </li>
    </ul>
    <p class="note">There is deliberately no single score here. A percentage invites a client to
      chase the number rather than the failures, and no honest percentage exists while roughly
      two thirds of the accessibility criteria on this page can only be judged by a person.</p>
  </section>

  <section aria-labelledby="budget-heading">
    <h2 id="budget-heading">Budgets</h2>
    <table>
      <caption class="visually-hidden">Budget results by module and metric</caption>
      <thead><tr><th scope="col">Check</th><th scope="col">Result</th><th scope="col">Measured</th><th scope="col">Limit</th></tr></thead>
      <tbody>
      ${report.budget.results
        .map(
          (r) => `<tr>
        <th scope="row"><code>${esc(r.module)}.${esc(r.metric)}</code></th>
        <td><span class="pill ${r.passed ? 'pill-pass' : 'pill-fail'}">${r.passed ? 'Pass' : 'Fail'}</span></td>
        <td>${esc(fmt(r.actual, r.unit))}</td>
        <td>${esc(fmt(r.limit, r.unit))}</td>
      </tr>`,
        )
        .join('\n      ')}
      </tbody>
    </table>
  </section>

  ${report.pages.map((page) => renderPage(page, report.pages.length > 1)).join('\n')}

  ${renderManual(report)}
</main>

<footer>
  <p>Generated by <strong>site-audit-cli ${esc(report.tool.version)}</strong> in
    ${(report.durationMs / 1000).toFixed(1)}s. Automated results reflect one cold load from one
    location on one connection. They are a floor, not a verdict.</p>
</footer>
</body>
</html>`;
}

function renderPage(page, showUrl) {
  const id = `page-${slug(page.url)}`;
  const defects = page.findings.filter((f) => f.kind !== 'manual' && f.severity !== 'info');
  const context = page.findings.filter((f) => f.kind !== 'manual' && f.severity === 'info');

  return `  <section aria-labelledby="${id}">
    <h2 id="${id}">${showUrl ? esc(page.url) : 'Findings'}</h2>
    ${page.metrics ? renderMetrics(page.metrics) : ''}
    ${
      defects.length === 0
        ? '<p class="note">No automated findings on this page. See the manual checks below before treating that as a pass.</p>'
        : defects.map(renderFinding).join('\n    ')
    }
    ${context.length > 0 ? `<h3>Context</h3>\n    ${context.map(renderFinding).join('\n    ')}` : ''}
  </section>`;
}

function renderMetrics(m) {
  const rows = [
    ['Largest Contentful Paint', m.lcpMs === null ? 'not measured' : `${Math.round(m.lcpMs)}ms`],
    ['Cumulative Layout Shift', m.cls.toFixed(3)],
    ['Total Blocking Time', `${Math.round(m.tbtMs)}ms`],
    ['Time to First Byte', `${Math.round(m.ttfbMs)}ms`],
    ['First Contentful Paint', m.fcpMs === null ? 'not measured' : `${Math.round(m.fcpMs)}ms`],
    ['Transfer size', `${formatBytes(m.totalBytes)} over ${m.requestCount} requests`],
  ];
  return `<h3>Lab metrics</h3>
    <dl class="metrics">
      ${rows.map(([k, v]) => `<div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join('\n      ')}
    </dl>
    <p class="note">Total Blocking Time stands in for Interaction to Next Paint, which cannot be
      measured without a real interaction. Field data from Chrome UX Report is the only source
      that describes actual visitors.</p>`;
}

function renderFinding(f) {
  return `<article class="finding sev-${f.severity}">
      <h3 class="finding-title">
        <span class="sev-tag">${esc(f.severity)}</span>
        ${esc(f.title)}${f.count > 1 ? ` <span class="count">${f.count} instances</span>` : ''}
      </h3>
      <p>${esc(f.detail)}</p>
      ${f.wcag.length > 0 ? `<p class="wcag">WCAG ${esc(f.wcag.join(', '))}</p>` : ''}
      ${f.evidence ? `<pre tabindex="0" role="group" aria-label="Evidence"><code>${esc(f.evidence)}</code></pre>` : ''}
      ${f.help ? `<p class="help"><strong>Next step.</strong> ${linkify(f.help)}</p>` : ''}
    </article>`;
}

function renderManual(report) {
  const manual = report.pages[0]?.findings.filter((f) => f.kind === 'manual') ?? [];
  if (manual.length === 0) return '';
  return `  <section aria-labelledby="manual-heading">
    <h2 id="manual-heading">Checks no scanner can make</h2>
    <p class="note">These are not findings and nothing above counts them. They are the WCAG 2.2
      Level A and AA requirements that no automated tool can decide, listed so that a clean
      automated report is not read as a conformant site.</p>
    ${manual
      .map(
        (m) => `<article class="finding sev-manual">
      <h3 class="finding-title"><span class="sev-tag">manual</span> ${esc(
        m.title.replace('Manual check required: ', ''),
      )} <span class="count">WCAG ${esc(m.wcag.join(', '))}</span></h3>
      <p><strong>Why a scanner cannot decide it.</strong> ${esc(m.detail)}</p>
      <p><strong>How to test.</strong> ${esc(m.help)}</p>
    </article>`,
      )
      .join('\n    ')}
  </section>`;
}

